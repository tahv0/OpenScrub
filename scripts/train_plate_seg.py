#!/usr/bin/env python3
"""Opt-in, local CUDA training from OpenScrub PR #5 reviewed plate polygons.

Commands:
  python scripts/train_plate_seg.py check --dataset plate-seg
  python scripts/train_plate_seg.py train --dataset plate-seg --weights /path/yolo-seg.pt \
      --versions-dir ~/.local/share/OpenScrub/plate_training --accept-ultralytics-license
  python scripts/train_plate_seg.py list --versions-dir ~/.local/share/OpenScrub/plate_training
  python scripts/train_plate_seg.py verify --versions-dir ... --version v...

Training requires separately installed CUDA PyTorch, Ultralytics (AGPL-3.0 /
Enterprise), onnx, and onnxruntime. Nothing installs or enables a model here.
Only human-verified polygons are eligible; autogenerated tracks and weak
bounding boxes are deliberately rejected. All artifacts remain local.
"""
import argparse
import contextlib
import datetime as dt
import hashlib
import json
import math
import os
import platform
import shutil
import sys
import tempfile
import time
import uuid
from collections import Counter
from pathlib import Path

import cv2
import numpy as np


class DataError(ValueError):
    pass


class TrainingProgress:
    """Scalar-only callbacks; no tensor reads, extra predictions or GPU syncs.

    Batch events are throttled to once a second. Stage changes and completed
    epochs/validation flush immediately so short operations remain observable.
    The leading newline keeps structured records separate from tqdm output.
    """
    def __init__(self, stream=None):
        self.stream = stream if stream is not None else sys.stdout
        self.last_emit = float("-inf")
        self.stage = None
        self.epoch = self.epochs = None
        self.batch = self.batches = 0
        self.validation_batch = self.validation_batches = 0
        self.validation_label = "Validating the trained candidate"

    def emit(self, stage, message, *, force=False, **fields):
        now = time.monotonic()
        if not force and stage == self.stage and now - self.last_emit < 1:
            return
        self.last_emit, self.stage = now, stage
        record = {"stage": stage, "message": message, **fields}
        self.stream.write("\nOPENSCRUB_PROGRESS " + json.dumps(record, allow_nan=False) + "\n")
        self.stream.flush()

    def attach_training(self, model):
        for name in ("on_train_epoch_start", "on_train_batch_end", "on_train_epoch_end"):
            model.add_callback(name, getattr(self, name))
        self._attach_validation(model)

    def attach_validation(self, model):
        self.validation_label = "Validating the trained candidate"
        self._attach_validation(model)

    def _attach_validation(self, model):
        for name in ("on_val_start", "on_val_batch_end", "on_val_end"):
            model.add_callback(name, getattr(self, name))

    def _training(self, force=False):
        self.emit("training", "Training epoch %d/%d: batch %d/%d" %
                  (self.epoch, self.epochs, self.batch, self.batches), force=force,
                  done=(self.epoch - 1) * self.batches + self.batch,
                  total=self.epochs * self.batches, unit="batches",
                  epoch=self.epoch, epochs=self.epochs,
                  batch=self.batch, batches=self.batches)

    def on_train_epoch_start(self, trainer):
        self.epoch, self.epochs = int(trainer.epoch) + 1, int(trainer.epochs)
        self.batch, self.batches = 0, len(trainer.train_loader)
        self.validation_label = "Validating epoch %d/%d" % (self.epoch, self.epochs)
        self._training()

    def on_train_batch_end(self, trainer):
        self.batch = min(self.batch + 1, self.batches)
        self._training()

    def on_train_epoch_end(self, trainer):
        self._training(force=True)

    def _validation(self, force=False):
        self.emit("candidate_validation", "%s: batch %d/%d" %
                  (self.validation_label, self.validation_batch, self.validation_batches),
                  force=force, done=self.validation_batch, total=self.validation_batches,
                  unit="batches")

    def on_val_start(self, validator):
        self.validation_batch, self.validation_batches = 0, len(validator.dataloader)
        self._validation(force=True)

    def on_val_batch_end(self, validator):
        self.validation_batch = min(self.validation_batch + 1, self.validation_batches)
        self._validation()

    def on_val_end(self, validator):
        self._validation(force=True)


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as src:
        for block in iter(lambda: src.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _private_dir(path):
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    if os.name != "nt":
        os.chmod(path, 0o700)


def _is_bounded(path, root):
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False


def _quad_valid(points):
    try:
        values = [float(x) for x in points]
        if len(values) != 8 or not all(math.isfinite(x) and 0 <= x <= 1
                                      for x in values):
            return False
        arr = np.array(values, dtype=np.float32).reshape((4, 2))
        return (cv2.isContourConvex(arr.reshape((-1, 1, 2))) and
                cv2.contourArea(arr) >= 0.0001)
    except (ValueError, TypeError):
        return False


def _dhash(image):
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    small = cv2.resize(gray, (9, 8), interpolation=cv2.INTER_AREA)
    result = 0
    for bit in (small[:, 1:] > small[:, :-1]).flat:
        result = (result << 1) | int(bit)
    return result


def validate_dataset(dataset, min_train_positive=12, min_val_positive=4,
                     min_negative_per_split=1):
    """Validate provenance, four-corner labels, split and near-duplicate leakage.

    'detect' exports with weak bbox pseudo-polygons are explicitly rejected:
    for segmentation, only human_quad positives are valid training targets.
    """
    root = Path(dataset).resolve(strict=True)
    manifest = root / "manifest.jsonl"
    if not manifest.is_file():
        raise DataError("Missing PR #5 manifest.jsonl; export with --task segment")
    if not (root / "data.yaml").is_file():
        raise DataError("Missing data.yaml; run prepare_plate_dataset.py --task segment")
    records = []
    counts = Counter()
    groups = {}
    hashes = {"train": [], "val": []}
    fingerprint = hashlib.sha256()
    with open(manifest, encoding="utf-8") as source:
        for line_no, line in enumerate(source, 1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
                split = row["split"]
                label = row["label"]
                quality = row["quality"]
                image_rel = row["image"]
                job = str(row["job"])
                track = int(row.get("track", -1))
                index = int(row["detection_index"])
            except (ValueError, KeyError, TypeError) as error:
                raise DataError("Invalid manifest row %d: %s" % (
                    line_no, error)) from error
            if split not in ("train", "val") or label not in ("positive", "negative"):
                raise DataError("Invalid split/label at manifest row %d" % line_no)
            if (label == "positive" and quality != "human_quad") or (
                    label == "negative" and quality != "human_hard_negative"):
                raise DataError("Unverified/weak label in row %d (%s); "
                                "segmentation requires manually reviewed quads"
                                % (line_no, quality))
            image_path = (root / image_rel).resolve()
            if (not isinstance(image_rel, str) or
                    Path(image_rel).is_absolute() or
                    not _is_bounded(image_path, root) or
                    not _is_bounded(image_path, (root / "images" / split).resolve())
                    or image_path.suffix.lower() not in (".jpg", ".jpeg", ".png")
                    or not image_path.is_file()):
                raise DataError("Missing or unsafe image at row %d" % line_no)
            image = cv2.imread(str(image_path))
            if image is None or min(image.shape[:2]) < 8:
                raise DataError("Unreadable/too-small image at row %d" % line_no)
            label_path = root / "labels" / split / (image_path.stem + ".txt")
            if not label_path.is_file() or label_path.is_symlink():
                raise DataError("Missing/unsafe YOLO label for %s" % image_path.name)
            lines = [s.strip() for s in label_path.read_text(
                encoding="utf-8").splitlines() if s.strip()]
            if label == "negative":
                if lines:
                    raise DataError("Hard negative has a positive label: %s"
                                    % label_path.name)
            elif (len(lines) != 1 or
                  lines[0].split()[0] != "0" or
                  not _quad_valid(lines[0].split()[1:])):
                raise DataError("Invalid 4-point YOLO polygon: %s" % label_path.name)
            group = (job, "track-%d" % track if track >= 0
                     else "frame-%d" % index)
            if group in groups and groups[group] != split:
                raise DataError("Same tracked object occurs in train and val: "
                                + str(group))
            groups[group] = split
            h = _dhash(image)
            image_sha = sha256_file(image_path)
            # Cross-split near-duplicates are a false validation success.
            # Restrict comparison to other split to allow redundant samples
            # within one split (though the PR #5 exporter already dedupes).
            opposite = "val" if split == "train" else "train"
            for previous, previous_sha in hashes[opposite]:
                if image_sha == previous_sha or bin(h ^ previous).count("1") <= 2:
                    raise DataError("Near-duplicate image in train and val: %s"
                                    % image_path.name)
            hashes[split].append((h, image_sha))
            counts[(split, label)] += 1
            fingerprint.update(line.strip().encode("utf-8"))
            fingerprint.update(image_sha.encode("ascii"))
            fingerprint.update(sha256_file(label_path).encode("ascii"))
            records.append(row)
    if not records:
        raise DataError("No reviewed samples found")
    for split, need in (("train", min_train_positive),
                        ("val", min_val_positive)):
        if counts[(split, "positive")] < need:
            raise DataError("%s needs at least %d verified plate polygons; "
                            "found %d" % (split, need, counts[(split, "positive")]))
        if counts[(split, "negative")] < min_negative_per_split:
            raise DataError("%s needs at least %d explicit false positives; "
                            "found %d" % (split, min_negative_per_split,
                                         counts[(split, "negative")]))
    return {"counts": {split: {kind: counts[(split, kind)]
                               for kind in ("positive", "negative")}
                       for split in ("train", "val")},
            "unique_track_groups": len(groups),
            "dataset_sha256": fingerprint.hexdigest(),
            "samples": len(records),
            "recording_count": len({str(row["job"]) for row in records}),
            "warning": ("Validation uses the same recording(s) as training; "
                        "test on unseen video before deployment."
                        if len({str(row["job"]) for row in records}) < 2
                        else None)}


def _cuda_info(device):
    try:
        import torch
    except (ImportError, OSError) as exc:
        raise RuntimeError(
            "Cannot import PyTorch using %s: %s: %s. "
            "Check the training environment and conflicting CUDA libraries; "
            "this does not necessarily mean PyTorch is missing."
            % (sys.executable, type(exc).__name__, exc)) from exc
    if not torch.cuda.is_available() or not torch.version.cuda:
        raise RuntimeError("CUDA unavailable: a CUDA-capable PyTorch build "
                           "and NVIDIA driver are required; CPU fallback is forbidden")
    if device < 0 or device >= torch.cuda.device_count():
        raise RuntimeError("CUDA device %d is not available" % device)
    return {"torch": torch.__version__, "cuda": torch.version.cuda,
            "gpu": torch.cuda.get_device_name(device)}


def training_environment(device=0):
    """Same script/import order as train, without reading a dataset or weights."""
    cuda = _cuda_info(device)
    try:
        import ultralytics
        import onnx
        import onnxruntime
    except (ImportError, OSError) as exc:
        raise RuntimeError("Training dependency import failed using %s: %s: %s"
                           % (sys.executable, type(exc).__name__, exc)) from exc
    return {"python": sys.executable, "isolated": bool(sys.flags.isolated), **cuda}


def _metrics(model, dataset_yaml, device, project, *, workers=0, batch=8, imgsz=640):
    # Reloading best.pt does not retain all training loader settings. Explicitly
    # preserve the caller's budget: GPU validation defaults otherwise spawn
    # workers and exchange tensors via /dev/shm, even after workers=0 training.
    results = model.val(data=str(dataset_yaml), split="val", device=device,
                        workers=workers, batch=batch, imgsz=imgsz, cache=False,
                        project=str(project), name="validation", exist_ok=True,
                        plots=False, verbose=False)
    seg = getattr(results, "seg", None)
    if seg is None:
        raise RuntimeError("Validation has no segmentation metrics")
    values = {"mask_map50": float(seg.map50), "mask_map": float(seg.map)}
    box = getattr(results, "box", None)
    if box is not None:
        values["box_map50"] = float(box.map50)
    if not all(math.isfinite(v) and 0 <= v <= 1 for v in values.values()):
        raise RuntimeError("Non-finite/out-of-range validation metrics")
    return values


def _smoke_onnx(path, imgsz):
    """Check the graph *and* execute a real CPU inference before publishing."""
    try:
        import onnx
        import onnxruntime as ort
    except ImportError as exc:
        raise RuntimeError("ONNX export validation requires onnx and "
                           "onnxruntime") from exc
    onnx.checker.check_model(str(path))
    session = ort.InferenceSession(str(path), providers=["CPUExecutionProvider"])
    inputs = session.get_inputs()
    if len(inputs) != 1:
        raise RuntimeError("Expected one ONNX image input")
    image = np.zeros((1, 3, imgsz, imgsz), dtype=np.float32)
    outputs = session.run(None, {inputs[0].name: image})
    if len(outputs) < 2 or not any(np.asarray(x).ndim == 4 for x in outputs):
        raise RuntimeError("Export is not a segmentation model (missing masks)")
    if not all(np.asarray(x).size and np.isfinite(x).all() for x in outputs):
        raise RuntimeError("ONNX smoke inference produced invalid output")
    return {"inputs": [str(i.shape) for i in inputs],
            "outputs": [list(np.asarray(x).shape) for x in outputs]}


@contextlib.contextmanager
def _exclusive(root):
    _private_dir(root)
    lock = root / ".training.lock"
    try:
        lock.mkdir(mode=0o700)
    except FileExistsError as exc:
        raise RuntimeError("Another training run holds %s; inspect it "
                           "before removing a stale lock" % lock) from exc
    try:
        yield
    finally:
        lock.rmdir()


def _atomic_json(path, data):
    temporary = path.with_name("." + path.name + "." + uuid.uuid4().hex + ".tmp")
    try:
        with open(temporary, "x", encoding="utf-8") as dest:
            json.dump(data, dest, indent=2, sort_keys=True)
            dest.write("\n")
        if os.name != "nt":
            os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def verify_version(versions_dir, version):
    # Only self-contained, candidate model versions; never auto-activate.
    if not isinstance(version, str) or not version.startswith("v") or (
            "/" in version or "\\" in version or ".." in version):
        raise DataError("Invalid model version")
    root = Path(versions_dir).resolve()
    folder = (root / version).resolve()
    if not _is_bounded(folder, root):
        raise DataError("Version escapes its directory")
    meta_file = folder / "manifest.json"
    if not meta_file.is_file():
        raise DataError("Model version not found: " + version)
    meta = json.loads(meta_file.read_text(encoding="utf-8"))
    if meta.get("version") != version or meta.get("status") != "candidate":
        raise DataError("Invalid model version metadata")
    for key, expected in meta.get("artifacts", {}).items():
        if key not in ("weights.pt", "model.onnx"):
            raise DataError("Unexpected artifact filename")
        path = folder / key
        if not path.is_file() or sha256_file(path) != expected:
            raise DataError("Missing or modified model artifact: " + key)
    if set(meta.get("artifacts", {})) != {"weights.pt", "model.onnx"}:
        raise DataError("Incomplete model artifacts")
    return meta


def train(args, report, progress=None):
    if not args.accept_ultralytics_license:
        raise RuntimeError("Ultralytics (weights, code and trained models) "
                           "are AGPL-3.0 / Enterprise licensed. Pass "
                           "--accept-ultralytics-license after reviewing terms.")
    weights = Path(args.weights).expanduser().resolve()
    if not weights.is_file() or weights.suffix.lower() != ".pt":
        raise DataError("Supply an already downloaded local *-seg.pt checkpoint")
    if (args.epochs < 1 or args.batch < 1 or args.imgsz < 128 or
            args.imgsz % 32 != 0 or args.workers < 0 or args.patience < 0):
        raise DataError("epochs/batch must be positive; imgsz >=128 and "
                        "divisible by 32; workers/patience nonnegative")
    if progress is None and getattr(args, "progress", False):
        progress = TrainingProgress()
    if progress:
        progress.emit("training", "Preparing the model and training loaders")
    cuda = _cuda_info(args.device)
    try:
        import ultralytics
        from ultralytics import YOLO
    except ImportError as exc:
        raise RuntimeError("Install optional ultralytics training dependency") from exc
    versions = Path(args.versions_dir).expanduser().resolve()
    with _exclusive(versions):
        stage = Path(tempfile.mkdtemp(prefix=".staging-", dir=versions))
        if os.name != "nt":
            os.chmod(stage, 0o700)
        try:
            # Build a validated, absolute-path dataset config ourselves,
            # independent of any arbitrary YAML supplied with the export.
            data_config = stage / "data.yaml"
            data_config.write_text(
                "path: " + json.dumps(str(Path(args.dataset).resolve())) + "\n"
                "train: images/train\nval: images/val\n"
                "names:\n  0: plate\n", encoding="utf-8")
            net = YOLO(str(weights))
            if net.task != "segment":
                raise RuntimeError("Checkpoint is not a YOLO instance "
                                   "segmentation model")
            if progress:
                progress.attach_training(net)
            net.train(data=str(data_config), epochs=args.epochs, batch=args.batch,
                      imgsz=args.imgsz, device=args.device, workers=args.workers,
                      patience=args.patience, seed=args.seed, amp=True,
                      cache=False, plots=False, save=True, verbose=False,
                      project=str(stage), name="training", exist_ok=True)
            best = stage / "training" / "weights" / "best.pt"
            if not best.is_file():
                raise RuntimeError("Training did not produce best.pt")
            trained = YOLO(str(best))
            if progress:
                progress.emit("candidate_validation", "Validating the trained candidate", force=True)
                progress.attach_validation(trained)
            results = _metrics(trained, data_config, args.device, stage,
                               workers=args.workers, batch=args.batch, imgsz=args.imgsz)
            if results["mask_map50"] < args.min_mask_map50:
                raise RuntimeError("Validation mask mAP50 %.3f below "
                                   "required %.3f: candidate rejected" %
                                   (results["mask_map50"], args.min_mask_map50))
            if progress:
                progress.emit("exporting", "Exporting the validated candidate to ONNX", metrics=results)
            result = trained.export(format="onnx", imgsz=args.imgsz,
                                    dynamic=False, half=False,
                                    simplify=False, nms=False, opset=17,
                                    device="cpu")
            exported = Path(result).resolve()
            if not exported.is_file():
                raise RuntimeError("ONNX export did not create a model file")
            if progress:
                progress.emit("checking", "Checking exported ONNX graph and inference", done=0, total=2, unit="checks")
            onnx_check = _smoke_onnx(exported, args.imgsz)
            # The dataset may have been edited while GPU training was
            # running. Never publish metadata for a different dataset.
            if progress:
                progress.emit("checking", "Checking that the training dataset is unchanged", force=True,
                              done=1, total=2, unit="checks")
            latest = validate_dataset(
                args.dataset, args.min_train_positive, args.min_val_positive,
                args.min_negative_per_split)
            if latest["dataset_sha256"] != report["dataset_sha256"]:
                raise RuntimeError("Training dataset changed during the run; "
                                   "candidate not published")
            if progress:
                progress.emit("checking", "Model and source checks passed; saving the candidate", force=True,
                              done=2, total=2, unit="checks")
            shutil.copy2(best, stage / "weights.pt")
            shutil.copy2(exported, stage / "model.onnx")
            version = "v" + dt.datetime.now(dt.timezone.utc).strftime(
                "%Y%m%dT%H%M%SZ") + "-" + uuid.uuid4().hex[:8]
            meta = {
                "schema": 1, "version": version, "status": "candidate",
                "created_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
                "deployment": "not_activated",
                "runtime": {"python": platform.python_version(),
                            "ultralytics": ultralytics.__version__, **cuda},
                "dataset": report,
                "source_checkpoint": {"name": weights.name,
                                      "sha256": sha256_file(weights)},
                "config": {"epochs": args.epochs, "batch": args.batch,
                           "imgsz": args.imgsz, "device": args.device,
                           "seed": args.seed, "patience": args.patience},
                "validation": results, "onnx_smoke": onnx_check,
                "artifacts": {"weights.pt": sha256_file(stage / "weights.pt"),
                              "model.onnx": sha256_file(stage / "model.onnx")},
                "notes": "Crop-trained segmentation candidate. Use the video-learning "
                         "refiner and its held-out coverage gate, not the full-frame PlateDetector.",
            }
            _atomic_json(stage / "manifest.json", meta)
            destination = versions / version
            os.rename(stage, destination)
            index_path = versions / "index.json"
            if index_path.is_file():
                index = json.loads(index_path.read_text(encoding="utf-8"))
                if not isinstance(index, dict):
                    raise DataError("Invalid model version index")
            else:
                index = {"schema": 1, "versions": []}
            index["versions"].append({
                "version": version, "status": "candidate",
                "mask_map50": results["mask_map50"],
                "model_sha256": meta["artifacts"]["model.onnx"]})
            _atomic_json(index_path, index)
            return meta
        finally:
            if stage.exists():
                shutil.rmtree(stage)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    environment = commands.add_parser("preflight", help="check this trainer's CUDA environment without training")
    environment.add_argument("--device", type=int, default=0)
    check = commands.add_parser("check", help="validate PR #5 segment dataset")
    train_cmd = commands.add_parser("train", help="CUDA train, validate, export")
    for sub in (check, train_cmd):
        sub.add_argument("--dataset", type=Path, required=True)
        sub.add_argument("--min-train-positive", type=int, default=12)
        sub.add_argument("--min-val-positive", type=int, default=4)
        sub.add_argument("--min-negative-per-split", type=int, default=1)
    train_cmd.add_argument("--weights", type=Path, required=True,
                           help="existing local pretrained *-seg.pt weights")
    train_cmd.add_argument("--accept-ultralytics-license", action="store_true")
    train_cmd.add_argument("--device", type=int, default=0)
    train_cmd.add_argument("--epochs", type=int, default=40)
    train_cmd.add_argument("--batch", type=int, default=8)
    train_cmd.add_argument("--imgsz", type=int, default=640)
    train_cmd.add_argument("--workers", type=int, default=4)
    train_cmd.add_argument("--patience", type=int, default=12)
    train_cmd.add_argument("--seed", type=int, default=42)
    train_cmd.add_argument("--min-mask-map50", type=float, default=0.25)
    train_cmd.add_argument("--progress", action="store_true",
                           help="emit structured scalar progress for the local learning UI")
    for sub in (train_cmd, commands.add_parser("list"),
                commands.add_parser("verify")):
        sub.add_argument("--versions-dir", type=Path, required=True)
    commands.choices["verify"].add_argument("--version", required=True)
    args = parser.parse_args(argv)
    progress = TrainingProgress() if getattr(args, "progress", False) else None
    try:
        if args.command == "preflight":
            print(json.dumps(training_environment(args.device), indent=2))
        elif args.command in ("check", "train"):
            if (args.min_train_positive < 1 or args.min_val_positive < 1 or
                    args.min_negative_per_split < 0):
                raise DataError("Sample requirements must be nonnegative; "
                                "train and val need positive polygon samples")
            if progress:
                progress.emit("checking", "Validating reviewed examples and dataset splits")
            report = validate_dataset(
                args.dataset, args.min_train_positive,
                args.min_val_positive, args.min_negative_per_split)
            print(json.dumps(report, indent=2))
            if args.command == "check":
                return 0
            if not 0 <= args.min_mask_map50 <= 1:
                raise DataError("--min-mask-map50 must be in [0, 1]")
            meta = train(args, report, progress=progress)
            print("Candidate saved: " + meta["version"])
            print("NOT activated; OpenScrub still uses its existing plate model")
        elif args.command == "list":
            index = Path(args.versions_dir).expanduser() / "index.json"
            rows = (json.loads(index.read_text(encoding="utf-8"))
                    if index.is_file() else {"schema": 1, "versions": []})
            print(json.dumps(rows, indent=2))
        else:
            meta = verify_version(args.versions_dir, args.version)
            print(json.dumps(meta, indent=2))
        return 0
    except (DataError, RuntimeError, OSError, ValueError) as error:
        print("ERROR: " + str(error), file=sys.stderr)
        return 2


